CREATE OR REPLACE FUNCTION public.generate_new_code(p_customer_id uuid, p_merchant_id uuid, p_loyalty_card_id uuid) 
RETURNS text 
LANGUAGE plpgsql
AS $function$
DECLARE
    new_code TEXT;
BEGIN
    new_code := gen_random_uuid()::text;
    INSERT INTO codes (code_string, customer_id, merchant_id, loyalty_card_id, status)
    VALUES (new_code, p_customer_id, p_merchant_id, p_loyalty_card_id, 'active');
    RETURN new_code;
END;
$function$;

CREATE OR REPLACE FUNCTION public.process_code_redemption(p_code_string text) 
RETURNS TABLE(
    status text, 
    message text, 
    customer_id uuid, 
    merchant_id uuid, 
    loyalty_card_id uuid, 
    current_punches integer, 
    punches_needed integer, 
    reward_description text
) 
LANGUAGE plpgsql
AS $function$
DECLARE
    v_code_record codes%ROWTYPE;
    v_loyalty_card_record loyalty_cards%ROWTYPE;
    v_loyalty_program_record loyalty_programs%ROWTYPE;
    v_new_code TEXT;
BEGIN
    SELECT * INTO v_code_record FROM codes WHERE code_string = p_code_string;
    IF NOT FOUND THEN 
        RETURN QUERY SELECT 'error', 'Code not found', NULL, NULL, NULL, NULL, NULL, NULL; 
        RETURN; 
    END IF;
    
    IF v_code_record.status = 'used' THEN 
        RETURN QUERY SELECT 'error', 'Code already used', v_code_record.customer_id, v_code_record.merchant_id, v_code_record.loyalty_card_id, NULL, NULL, NULL; 
        RETURN; 
    END IF;
    
    IF v_code_record.status = 'invalid' THEN 
        RETURN QUERY SELECT 'error', 'Code is invalid', v_code_record.customer_id, v_code_record.merchant_id, v_code_record.loyalty_card_id, NULL, NULL, NULL; 
        RETURN; 
    END IF;
    
    UPDATE codes SET status = 'used', used_at = NOW() WHERE id = v_code_record.id;
    
    SELECT * INTO v_loyalty_card_record FROM loyalty_cards WHERE id = v_code_record.loyalty_card_id;
    SELECT * INTO v_loyalty_program_record FROM loyalty_programs WHERE id = v_loyalty_card_record.loyalty_program_id;
    
    UPDATE loyalty_cards SET current_punches = v_loyalty_card_record.current_punches + 1 WHERE id = v_loyalty_card_record.id RETURNING * INTO v_loyalty_card_record;
    
    IF v_loyalty_card_record.current_punches >= v_loyalty_program_record.punches_required THEN
        UPDATE loyalty_cards SET status = 'completed' WHERE id = v_loyalty_card_record.id;
        INSERT INTO loyalty_cards (customer_id, merchant_id, loyalty_program_id, current_punches, status)
        VALUES (v_loyalty_card_record.customer_id, v_loyalty_card_record.merchant_id, v_loyalty_card_record.loyalty_program_id, 0, 'active');
        v_new_code := generate_new_code(v_loyalty_card_record.customer_id, v_loyalty_card_record.merchant_id, (SELECT id FROM loyalty_cards WHERE customer_id = v_loyalty_card_record.customer_id AND status = 'active' ORDER BY id DESC LIMIT 1));
        RETURN QUERY SELECT 'success', 'Card complete! Reward: ' || v_loyalty_program_record.reward_description || '. New code generated: ' || v_new_code, v_code_record.customer_id, v_code_record.merchant_id, v_code_record.loyalty_card_id, v_loyalty_card_record.current_punches, 0, v_loyalty_program_record.reward_description;
    ELSE
        v_new_code := generate_new_code(v_loyalty_card_record.customer_id, v_loyalty_card_record.merchant_id, v_loyalty_card_record.id);
        RETURN QUERY SELECT 'success', 'Punch added! Customer has ' || (v_loyalty_program_record.punches_required - v_loyalty_card_record.current_punches) || ' punches left. New code generated: ' || v_new_code, v_code_record.customer_id, v_code_record.merchant_id, v_code_record.loyalty_card_id, v_loyalty_card_record.current_punches, (v_loyalty_program_record.punches_required - v_loyalty_card_record.current_punches), v_loyalty_program_record.reward_description;
    END IF;
EXCEPTION 
    WHEN OTHERS THEN 
        RETURN QUERY SELECT 'error', SQLERRM, NULL, NULL, NULL, NULL, NULL, NULL;
END;
$function$;

CREATE OR REPLACE FUNCTION public.create_loyalty_for_merchant(merchant_id uuid) 
RETURNS void 
LANGUAGE plpgsql
AS $function$
DECLARE
    m RECORD;
    new_loyalty_program_id UUID;
    default_customer_id UUID;
BEGIN
    SELECT * INTO m FROM merchants WHERE id = merchant_id;
    IF m.is_loyalty_program_eligible THEN
        INSERT INTO loyalty_programs (merchant_id, type, reward_description, punches_required, perk_description)
        VALUES (m.id, 'stamp_card', 'Default reward', 6, 'Default perk')
        RETURNING id INTO new_loyalty_program_id;
        
        INSERT INTO customers (merchant_id, full_name, phone_number, zone, created_at)
        VALUES (m.id, m.name || ' Default Customer', 'N/A_' || m.id::text, 'Default', NOW())
        ON CONFLICT (phone_number) DO NOTHING
        RETURNING id INTO default_customer_id;
        
        IF default_customer_id IS NOT NULL THEN
            INSERT INTO loyalty_cards (customer_id, merchant_id, loyalty_program_id, current_punches, status)
            VALUES (default_customer_id, m.id, new_loyalty_program_id, 0, 'active');
        END IF;
    END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.redeem_code() 
RETURNS trigger 
LANGUAGE plpgsql 
SECURITY DEFINER
AS $function$
DECLARE
    current_card_punches INT;
    punches_required INT;
    free_reward_code TEXT;
BEGIN
    IF NEW.status = 'active' THEN
        UPDATE codes SET status = 'used', used_at = NOW() WHERE id = NEW.id;
        
        SELECT lc.current_punches, lp.punches_required INTO current_card_punches, punches_required
        FROM loyalty_cards lc 
        JOIN loyalty_programs lp ON lc.loyalty_program_id = lp.id 
        WHERE lc.id = NEW.loyalty_card_id;
        
        UPDATE loyalty_cards SET current_punches = current_card_punches + 1 WHERE id = NEW.loyalty_card_id;
        
        IF current_card_punches + 1 >= punches_required THEN
            free_reward_code := gen_random_uuid()::text;
            INSERT INTO codes (code_string, customer_id, merchant_id, loyalty_card_id, status, generated_at)
            VALUES (free_reward_code, NEW.customer_id, NEW.merchant_id, NEW.loyalty_card_id, 'active', NOW());
            UPDATE loyalty_cards SET status = 'redeemed' WHERE id = NEW.loyalty_card_id;
        END IF;
    END IF;
    RETURN NEW;
END;
$function$;

-- Function to notify about new merchant applications
CREATE OR REPLACE FUNCTION public.notify_new_merchant_application()
RETURNS TRIGGER 
LANGUAGE plpgsql 
SECURITY DEFINER
AS $$
BEGIN
    PERFORM net.http_post(
        url := 'https://gucrinbliukkhubtxhqn.supabase.co/functions/v1/merchant-application-alert',
        headers := '{"Content-Type": "application/json"}'::jsonb,
        body := jsonb_build_object(
            'merchant_id', NEW.id,
            'name', NEW.name,
            'contact_email', NEW.contact_email,
            'contact_phone', NEW.contact_phone,
            'business_type', NEW.business_type,
            'subscription_status', NEW.subscription_status
        )
    );
    RETURN NEW;
EXCEPTION
    WHEN OTHERS THEN
        -- Log error but don't fail the insert
        RAISE WARNING 'Failed to send merchant application notification: %', SQLERRM;
        RETURN NEW;
END;
$$;

